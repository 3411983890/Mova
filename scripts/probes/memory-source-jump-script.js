const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
document.querySelector('#settings-button').click();
document.querySelector('[data-settings-item="memory"]').click();
await sleep(300);
const page = document.querySelector('#settings-page-memory');
const search = page.querySelector('input[type="search"]');
Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(search, 'PostgreSQL');
search.dispatchEvent(new Event('input', { bubbles: true }));
page.querySelector('.memory-search button[type="submit"]').click();
await sleep(500);
const hits = [...page.querySelectorAll('.memory-entry')];
if (!hits.length) throw new Error('No search hits for seeded history');
const sourceButton = [...page.querySelectorAll('button')].find(button => button.textContent.includes('查看来源'));
if (!sourceButton) throw new Error('Source button missing from search hit');
sourceButton.click();
await sleep(800);
const target = document.querySelector('#qa-markdown-assistant');
const settingsHidden = document.querySelector('#settings-view').hidden;
return { hits: hits.length, settingsHidden, chatShown: !document.querySelector('#conversation').hidden, target: Boolean(target), focused: document.activeElement?.id || '', title: document.querySelector('#chat-header-title').textContent };
