const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
document.querySelector('#settings-button').click();
document.querySelector('[data-settings-item="memory"]').click();
await sleep(350);
const page = document.querySelector('#settings-page-memory');
if (page.hidden || !page.textContent.includes('自动提取记忆')) throw new Error('Memory page failed first open');
if (!page.textContent.includes('记忆总条数上限')) throw new Error('Max memory setting missing');
if (!page.textContent.includes('repository.json')) throw new Error('Storage path missing');
document.querySelector('[data-settings-item="config"]').click();
await sleep(150);
document.querySelector('[data-settings-item="memory"]').click();
await sleep(350);
if (page.hidden || !page.textContent.includes('自动提取记忆')) throw new Error('Memory page disappeared on second open');
const toggle = page.querySelector('[role="switch"][aria-label="自动提取记忆"]');
if (!toggle) throw new Error('Auto-extract toggle missing');
const before = toggle.getAttribute('aria-checked');
toggle.click();
await sleep(300);
const after = page.querySelector('[role="switch"][aria-label="自动提取记忆"]').getAttribute('aria-checked');
if (before === after) throw new Error('Toggle did not persist');
const stored = await window.movaDesktop.memory.read();
return { secondOpen: true, autoExtract: stored.value.settings.autoExtract, mode: document.querySelector('#mode-label').textContent, rows: page.querySelectorAll('.memory-entry').length };
